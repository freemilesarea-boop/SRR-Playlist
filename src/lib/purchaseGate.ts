/**
 * purchaseGate — 네이티브 앱(iOS/Android)에서 결제 진입점을 감춘다.
 *
 * 왜 필요한가
 * -----------
 * 구글 플레이 결제 정책은 앱 안에서 파는 디지털 구독을 Google Play 결제로만
 * 팔도록 하고, 외부 결제 페이지로 내보내는 것(링크아웃)을 금지한다. 애플도 같다.
 * 우리 결제는 PayApp 웹 결제창을 시스템 브라우저로 여는 방식이라, 앱에 결제
 * 버튼·가격·업그레이드 유도가 보이면 심사에서 반려된다.
 *
 * 막는 것과 막지 않는 것
 * ---------------------
 * 막는 것은 "앱 안에서 새로 사는 경로" 뿐이다. 정책이 문제 삼는 것은 구매
 * 행위이지 이용 자체가 아니다:
 *
 *   - 막는다   — 요금제 카드의 결제 CTA, 가격, /pricing 같은 결제 화면,
 *                구독 유도 배너·모달의 결제 버튼
 *   - 안 막는다 — 웹에서 이미 결제한 사용자의 앱 이용, 현재 구독 상태 표시,
 *                구독 해지(오히려 열어두는 편이 정책상 안전하다)
 *
 * 웹/PWA 는 스토어 정책 대상이 아니므로 아무것도 바뀌지 않는다. 그래서 판정은
 * `isNativeApp()` 하나에만 걸려 있다.
 */
import { isNativeApp } from '@/lib/native';

/**
 * 결제/구매 UI 를 보여도 되는가.
 *
 * 새 결제 진입점을 만들 때는 반드시 이 함수로 감쌀 것. 화면마다 `isNativeApp()`
 * 을 직접 부르면 나중에 정책이 바뀌었을 때 빠뜨리는 곳이 생긴다.
 */
export function canShowPurchaseUi(): boolean {
  return !isNativeApp();
}

/** 앱에서 결제 화면에 들어왔을 때 보여줄 안내 문구. */
export const PURCHASE_UNAVAILABLE_TITLE = '앱에서는 요금제 가입을 할 수 없어요';
export const PURCHASE_UNAVAILABLE_BODY =
  '이미 이용 중인 요금제는 앱에서 그대로 사용하실 수 있어요.';
