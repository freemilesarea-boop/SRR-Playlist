## 계약 핵심 요약

* 음원의 저작권 및 저작인접권은 원칙적으로 아티스트에게 귀속됩니다.
* 회사는 서비스 운영에 필요한 범위 내에서만 비독점적 이용 권한을 가집니다.
* 정산은 월 1회 진행됩니다.
* 지급은 익월 영업일 기준 15일에 진행됩니다.
* 최소 지급 기준은 50,000원입니다.
* 아티스트는 언제든 음원 송신 중단을 요청할 수 있습니다.
* 본 계약은 전자서명 방식으로 체결됩니다.

---

# 제1조 (목적)

본 계약은 SRR Playlist(이하 "회사")가 운영하는 음악 스트리밍 및 큐레이션 서비스 내에서 아티스트의 음원을 송신·노출·정산하기 위한 권리 및 의무를 정함을 목적으로 합니다.

---

# 제2조 (권리 귀속)

1. 본 계약은 음원에 대한 저작권 및 저작인접권의 양도를 의미하지 않습니다.
2. 음원에 대한 권리는 원칙적으로 아티스트에게 귀속됩니다.
3. 회사는 서비스 운영에 필요한 범위 내에서만 비독점적 이용 권한을 가집니다.

---

# 제3조 (서비스 이용 허락)

아티스트는 회사가 다음 행위를 수행하는 것에 동의합니다.

1. SRR Playlist 서비스 내 스트리밍 송신
2. 플레이리스트 큐레이션 및 추천 노출
3. 서비스 홍보를 위한 일부 구간 미리듣기 제공
4. 서비스 UI·앱·웹 환경 내 음원 재생

회사는 본 계약에서 정한 목적 외로 음원을 사용하지 않습니다.

---

# 제4조 (권리 보증)

1. 아티스트는 등록 음원에 대한 권리를 적법하게 보유하거나 이용 허락을 받았음을 보증합니다.
2. 제3자의 권리를 침해하는 음원 등록으로 발생하는 모든 책임은 아티스트에게 있습니다.
3. 회사는 권리 침해 신고 또는 분쟁 발생 시 음원 송신을 제한할 수 있습니다.

---

# 제5조 (AI 생성 음원)

1. 아티스트는 AI 생성 도구를 사용한 경우에도 상업적 이용 가능 권한을 보유함을 보증합니다.
2. AI 생성 음원으로 인해 발생하는 제3자 분쟁의 책임은 아티스트에게 있습니다.

---

# 제6조 (정산 기준)

1. 회사는 서비스 정책상 유효하다고 판단되는 스트림을 기준으로 정산합니다.
2. 다음 항목은 정산 대상에서 제외될 수 있습니다.

   * 비정상 반복 재생
   * 자동화·봇 트래픽
   * 어뷰징 행위
   * 기타 회사 정책상 무효 스트림
3. 정산 방식은 회사 정책에 따라 운영되며, 변경 시 사전 공지합니다.

---

# 제7조 (수수료 및 지급)

1. 회사는 플랫폼 운영 수수료 및 정책상 필요한 비용을 공제할 수 있습니다.
2. 최소 지급 기준은 50,000원이며, 미달 금액은 다음 달로 자동 이월됩니다.
3. 회사는 관련 법령에 따라 원천징수 세액을 공제 후 지급할 수 있습니다.

---

# 제8조 (정산 일정)

1. 정산 대상 기간은 매월 1일 00:00부터 말일 23:59까지로 합니다. (Asia/Seoul 기준)

2. 회사는 매월 발생한 정산 내역을 익월 초 아티스트 대시보드 및 시스템을 통해 제공합니다.

3. 지급 대상 정산금은 익월 영업일 기준 15일에 아티스트가 등록한 정산 계좌로 입금됩니다.

4. 단, 다음 각 호의 사유가 발생하는 경우 지급 일정이 조정될 수 있습니다.

   * 금융기관 점검 또는 공휴일
   * 세무·법률 검토 필요
   * 비정상 스트림 또는 어뷰징 검토
   * 계좌 정보 오류
   * 기타 회사의 합리적인 운영상 사유

5. 최소 지급 기준 미달 금액은 다음 정산월로 자동 이월됩니다.

---

# 제9조 (이의제기)

1. 아티스트는 정산 내역에 대해 일정 기간 내 이의를 제기할 수 있습니다.
2. 회사는 접수된 내용을 검토 후 결과를 안내합니다.

---

# 제10조 (송신 중단)

1. 아티스트는 언제든 음원의 송신 중단을 요청할 수 있습니다.
2. 회사는 합리적인 기간 내 송신을 중단합니다.
3. 중단 이전 발생한 정산은 정상 처리됩니다.

---

# 제11조 (계약 해지)

다음 사유 발생 시 계약은 종료될 수 있습니다.

1. 계약 위반
2. 권리 침해 음원 반복 등록
3. 서비스 종료
4. 회원 탈퇴

---

# 제12조 (개인정보 처리)

1. 회사는 관련 법령 및 개인정보처리방침에 따라 정보를 처리합니다.
2. 정산 및 세무 처리를 위해 필요한 정보를 보관할 수 있습니다.

---

# 제13조 (전자서명)

1. 본 계약은 온라인 전자 동의 방식으로 체결됩니다.
2. 회사는 다음 정보를 기록할 수 있습니다.

   * 동의 시각
   * IP 주소
   * 접속 환경
   * 계약 버전
3. 전자 동의는 서면 계약과 동일한 효력을 가집니다.

---

# 제14조 (계약 변경)

1. 회사는 서비스 운영, 정책 변경, 법령 개정, 정산 구조 변경 등의 사유로 본 계약 내용을 수정할 수 있습니다.

2. 계약 내용이 변경되는 경우 회사는 시행일 기준 최소 14일 전에 서비스 내 공지 또는 이메일 등의 방법으로 사전 안내합니다.

3. 계약 내용의 중대한 변경이 발생하는 경우 회사는 아티스트에게 재동의 절차를 요청할 수 있습니다.

4. 아티스트가 변경된 계약에 재동의하지 않는 경우 회사는 음원 송신 및 정산 서비스를 제한하거나 계약을 종료할 수 있습니다.

---

# 제15조 (분쟁 해결)

1. 본 계약은 대한민국 법령에 따릅니다.
2. 분쟁 발생 시 회사 본점 소재지 관할 법원을 제1심 관할로 합니다.

